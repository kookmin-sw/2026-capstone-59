def resolve_activity_guide(current_required_step: Optional[RequiredStepInfo]) -> str:
    """현재 필수 Step에 맞는 활동 가이드 텍스트를 반환한다.

    Args:
        current_required_step: 현재 진행 중인 필수 Step. None이면 자유 생성 모드.

    Returns:
        프롬프트에 주입할 가이드 텍스트 문자열.
    """
    if current_required_step is None:
        return _FREE_MODE_GUIDE

    guide = ACTIVITY_GUIDES.get(current_required_step.name)
    if guide is None:
        logger.warning(
            json.dumps(
                {"event": "activity_guide_lookup_miss", "name": current_required_step.name},
                ensure_ascii=False,
            )
        )
        return _FREE_MODE_GUIDE

    return guide
